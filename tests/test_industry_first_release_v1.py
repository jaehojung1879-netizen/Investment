def test_new_layout_four_monthly_columns():
    p = C.parse_motie_text(NEW)
    assert p["columns"] == ["2025-10", "2026-08", "2026-09", "2026-10"]
    assert p["rows"]["반도체"] == {"2025-10": 15701.0, "2026-08": 46651.0, "2026-09": 60295.0, "2026-10": 56438.0}


def test_old_layout_without_parentheses_or_trailing_dot():
    p = C.parse_motie_text(OLD)
    assert p["columns"] == ["2023-04", "2024-02", "2024-03", "2024-04"]
    assert p["rows"]["석유제품"]["2024-04"] == 4368.0


def test_half_year_layout_drops_cumulative_columns():
    p = C.parse_motie_text(HALF)
    assert p["columns"] == ["2024-06", "2025-05", "2025-06"]          # the Jan-Jun totals are not months
    assert p["rows"]["반도체"] == {"2024-06": 13420.0, "2025-05": 13794.0, "2025-06": 14972.0}


def test_title_pattern_accepts_combined_half_year_and_annual_reports():
    for t in ("2026년 6월 및 상반기 수출입 동향 산업통상부 2026.07.01 48p",
              "2023년 12월 및 연간 수출입 동향 산업통상자원부 2024.01.01 48p",
              "2026년 10월 수출입 동향 산업통상부 2026.11.01 36p"):
        assert C.MOTIE.match(t)
    assert not C.MOTIE.match("2026년 10월 정보통신산업(ICT) 수출입 동향 산업통상부 2026.11.15 24p")
