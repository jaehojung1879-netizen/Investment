"""Narrow price-evidence pilot: bounded access and a static producer check.

No third-party code execution, no prices/returns, no issuer inference from names.
"""
from __future__ import annotations

import ast
import hashlib
import json
from pathlib import Path
from urllib.parse import urlsplit

PILOT = ('JWN', 'ADS', 'CTXS', 'ALXN', 'ATVI', 'ABC', 'PXD', 'MRO')
FOCUS = PILOT[:3]
MAX_BYTES = 5 * 1024 * 1024


def fingerprint(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def inspect_generator(source):
    """Prove ONLY the pinned script's normal-path gap; do not condemn its CSVs."""
    raw = source if isinstance(source, bytes) else source.encode()
    tree = ast.parse(raw)
    findings = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Try): continue
        only_print = (len(node.body) == 1 and isinstance(node.body[0], ast.Expr)
                      and isinstance(node.body[0].value, ast.Call)
                      and isinstance(node.body[0].value.func, ast.Name)
                      and node.body[0].value.func.id == 'print')
        for handler in node.handlers:
            if not (only_print and isinstance(handler.type, ast.Name) and handler.type.id == 'KeyError'):
                continue
            calls = [n for n in ast.walk(handler) if isinstance(n, ast.Call)]
            readers = [n.lineno for n in calls if isinstance(n.func, ast.Attribute) and n.func.attr == 'DataReader']
            writers = [n.lineno for n in calls if isinstance(n.func, ast.Attribute) and n.func.attr == 'to_csv']
            if readers and writers:
                findings.append({'status': 'VERIFIED_INCORRECT_DECLARED_NORMAL_REPRODUCTION_PATH',
                                 'tryLine': node.lineno, 'exceptLine': handler.lineno,
                                 'readerLines': readers, 'writerLines': writers})
    return {'sourceSha256': hashlib.sha256(raw).hexdigest(), 'findings': findings,
            'doesNotProve': 'Prices incorrect, nonexistent, or generated by no other historical code version'}


def probe(requests_to_make, output, *, fetch, now, sleep):
    """One attempt per URL; stop a refused host, never bypass/redirect/retry."""
    output = Path(output).resolve()
    if any((p / '.git/HEAD').is_file() or (p / '.git').is_file() for p in (output, *output.parents)):
        raise ValueError('EVIDENCE_STAGING_OUTSIDE_GIT_REQUIRED')
    output.mkdir(mode=0o700, exist_ok=True)
    if len(requests_to_make) > 8: raise ValueError('PILOT_REQUEST_BUDGET')
    stopped, records = set(), []
    for identity, url in requests_to_make:
        host = urlsplit(url).hostname
        if urlsplit(url).scheme != 'https' or not host or urlsplit(url).username:
            raise ValueError('INVALID_EVIDENCE_URL')
        if host in stopped:
            records.append({'id': identity, 'url': url, 'state': 'NOT_ATTEMPTED_HOST_STOP'})
            continue
        record = {'id': identity, 'url': url, 'acquiredAt': now()}
        try:
            status, data, location = fetch(url)
            if len(data) > MAX_BYTES: raise ValueError('EVIDENCE_BYTE_BUDGET')
            record.update(httpStatus=status, responseSha256=hashlib.sha256(data).hexdigest(), bytes=len(data))
            if status == 200:
                path = output / (record['responseSha256'] + '.bin')
                if not path.exists():
                    with path.open('xb') as handle: handle.write(data)
                    path.chmod(0o600)
                record.update(state='RETRIEVED_NOT_YET_VALIDATED', localFilename=path.name)
            elif status in (401, 403, 429):
                record['state'] = 'PROVIDER_HTTP_' + str(status);stopped.add(host)
            elif 300 <= status < 400:
                record.update(state='REDIRECT_NOT_FOLLOWED', redirectLocation=location)
            else:
                record['state'] = 'PROVIDER_HTTP_' + str(status)
        except ConnectionError as exc:
            record.update(state='PROXY_CONNECT_403' if '403' in str(exc) else 'NETWORK_FAILURE',
                          error=str(exc)[:350], responseSha256=None)
            stopped.add(host)
        record['requestRecordSha256'] = fingerprint(record)
        records.append(record);sleep(.5)
    return records
